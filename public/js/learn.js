  /* ─────────── Мини-игра: угадай бота ─────────── */
  const SUSPECTS = ['tit_for_tat', 'grim', 'pavlov', 'always_d', 'random', 'tf2t', 'detective', 'alternator'];
  const GUESS_ROUNDS = 12;

  function mountGuess(root) {
    const pd = GT.getGame('dilemma');
    const pool = GT.strategies.matrix.filter((s) => SUSPECTS.includes(s.id));
    let st;
    function start() {
      const secret = pool[Math.floor(Math.random() * pool.length)];
      const others = pool.filter((s) => s !== secret).sort(() => Math.random() - 0.5).slice(0, 3);
      st = { secret, options: others.concat(secret).sort(() => Math.random() - 0.5), me: [], bot: [], score: [0, 0], mem: {}, rng: GT.rng(Math.floor(Math.random() * 1e9)), guessed: null };
      draw();
    }
    function botMove() {
      const r = st.me.length;
      return pd.sanitize(st.secret.play({
        round: r, rounds: GUESS_ROUNDS, my: st.bot, opp: st.me, myLast: st.bot[r - 1], oppLast: st.me[r - 1],
        myScore: st.score[1], oppScore: st.score[0], state: {}, params: pd.defaults, mem: st.mem, rng: st.rng,
      }));
    }
    function play(move) {
      if (st.me.length >= GUESS_ROUNDS) return;
      const b = botMove();
      const pay = pd.defaults.payoff[move + b];
      st.me.push(move); st.bot.push(b);
      st.score[0] += pay[0]; st.score[1] += pay[1];
      draw();
    }
    function draw() {
      const done = st.me.length >= GUESS_ROUNDS;
      root.innerHTML = `<div class="card card-pad">
        <div class="panel-title">Угадай бота <span class="comment">// сыграйте ${GUESS_ROUNDS} раундов дилеммы против скрытой стратегии и определите, кто это</span></div>
        <div class="strip big" style="grid-template-rows:auto auto;margin-bottom:12px">
          <span class="lbl a">вы</span><span class="lbl b">бот</span>${Array.from({ length: GUESS_ROUNDS }, (_, k) => UI.cellHtml(st.me[k] ? { text: st.me[k], cls: st.me[k] === 'C' ? 'good' : 'bad' } : null) + UI.cellHtml(st.bot[k] ? { text: st.bot[k], cls: st.bot[k] === 'C' ? 'good' : 'bad' } : null)).join('')}
        </div>
        <div class="row"><span class="mono">счёт ${st.score[0]} : ${st.score[1]}</span><span class="spacer"></span>
          ${done ? '' : `<button class="btn btn-primary" data-move="C">C — сотрудничать</button><button class="btn btn-danger" data-move="D">D — предать</button>`}</div>
        ${done ? `<div style="margin-top:16px"><div class="label" style="margin-bottom:8px">кто это был?</div><div class="chips">${st.options.map((o) => {
          const cls = st.guessed ? (o === st.secret ? 'on' : o.id === st.guessed ? 'bad' : '') : '';
          return `<span class="chip ${cls}" data-guess="${o.id}">${esc(o.name)}</span>`;
        }).join('')}</div>
          ${st.guessed ? `<p style="margin:14px 0 0">${st.guessed === st.secret.id ? '<b class="good">Верно!</b>' : '<b class="bad">Мимо.</b>'} Это был «${esc(st.secret.name)}»: ${esc(st.secret.desc)}</p>
            <button class="btn btn-sm" data-again style="margin-top:12px">Ещё раз</button>` : ''}</div>`
          : '<p class="comment" style="margin:12px 0 0">// подсказка: проверьте, мстит ли бот, прощает ли и что он делает первым ходом</p>'}
      </div>`;
    }
    root.addEventListener('click', (e) => {
      const m = e.target.closest('[data-move]');
      if (m) return play(m.dataset.move);
      const g = e.target.closest('[data-guess]');
      if (g && !st.guessed) { st.guessed = g.dataset.guess; draw(); return; }
      if (e.target.closest('[data-again]')) start();
    });
    start();
  }

  /* ─────────── Страницы ─────────── */
